/* ------------------------------------------------------------------
   Aufbereitung in das von der App genutzte Objektformat.
   Neue Lebensmittel einfach oben in FOOD_ROWS ergänzen — die ID wird
   automatisch aus dem Namen gebildet.
   ------------------------------------------------------------------ */
function slugifyFoodName(name){
  return name.toLowerCase()
    .replace(/ä/g,'ae').replace(/ö/g,'oe').replace(/ü/g,'ue').replace(/ß/g,'ss')
    .replace(/[^a-z0-9]+/g,'_')
    .replace(/^_+|_+$/g,'');
}

